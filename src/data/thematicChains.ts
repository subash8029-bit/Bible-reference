export function searchThemes(query: string): ThematicTopic[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return THEMATIC_TOPICS;

  return THEMATIC_TOPICS.filter(t => 
    t.titleEn.toLowerCase().includes(clean) ||
    t.titleTe.toLowerCase().includes(clean) ||
    t.descriptionEn.toLowerCase().includes(clean) ||
    t.descriptionTe.toLowerCase().includes(clean) ||
    t.verses.some(v => 
      v.refEn.toLowerCase().includes(clean) ||
      v.refTe.toLowerCase().includes(clean) ||
      v.textEn.toLowerCase().includes(clean) ||
      v.textTe.toLowerCase().includes(clean)
    )
  );
}
