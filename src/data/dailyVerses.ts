/**
 * Gets the official verse of the day based on the current calendar date (1-31).
 */
export function getTodaysVerse(): DailyVerseItem {
  const day = new Date().getDate(); // 1 - 31
  const found = DAILY_VERSES.find((v) => v.dayIndex === day);
  return found || DAILY_VERSES[0];
}

/**
 * Returns a random daily verse, optionally excluding the current one.
 */
export function getRandomDailyVerse(currentId?: string): DailyVerseItem {
  const pool = currentId ? DAILY_VERSES.filter((v) => v.id !== currentId) : DAILY_VERSES;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || DAILY_VERSES[0];
}
